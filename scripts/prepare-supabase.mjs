import { mkdir, copyFile, readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const target = new URL('supabase/functions/nornails-api/', root);
await mkdir(new URL('backend/', target), { recursive: true });
const queries = new Set();
for (const file of ['backend/worker.mjs', 'backend/connect.mjs']) {
  const source = await readFile(new URL(file, root), 'utf8');
  for (const match of source.matchAll(/\.prepare\('([^']+)'\)/g)) queries.add(match[1]);
}
const allowlist = '// Generated by scripts/prepare-supabase.mjs. No user-supplied SQL.\nexport const statements = ' + JSON.stringify([...queries], null, 2) + ';\n';
await writeFile(new URL('backend/statements.mjs', root), allowlist);
for (const file of ['commerce.js', 'backend/worker.mjs', 'backend/connect.mjs', 'backend/postgres.mjs', 'backend/statements.mjs']) {
  await copyFile(new URL(file, root), new URL(file, target));
}
console.log('Supabase function sources prepared.');
